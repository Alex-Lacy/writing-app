import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).click();
const ta = p.locator('.helper-input textarea');
await ta.fill(Array.from({ length: 60 }, (_, i) => `line ${i}`).join('\n'));
const area = await p.locator('.helper').evaluate((e) => e.clientHeight);
console.log('auto height', await ta.evaluate((e) => e.offsetHeight), 'area/3', Math.round(area / 3));
const g = await p.locator('.helper-grip').boundingBox();
await p.mouse.move(g.x + g.width / 2, g.y + 4); await p.mouse.down(); await p.mouse.move(g.x + g.width / 2, g.y + 200, { steps: 5 }); await p.mouse.up();
console.log('after drag down', await ta.evaluate((e) => e.offsetHeight));
await p.screenshot({ path: '/tmp/hp-panel.png' });
await p.getByRole('button', { name: '⇱ Pop out' }).click();
console.log('window:', await p.locator('.helper-window').count(), '| text kept:', (await p.locator('.helper-window textarea').inputValue()).slice(0, 12));
await p.screenshot({ path: '/tmp/hp-window.png' });
await p.reload(); await p.waitForTimeout(1000);
await p.locator('.modal-scrim:not(.helper-scrim) .modal-head .icon').first().click({ timeout: 1500 }).catch(() => {});
console.log('window after reload:', await p.locator('.helper-window').count());
await p.locator('.helper-window .modal-head .icon').click();
console.log('back in panel:', await p.locator('.story-panel .helper, .panel .helper').count(), '| window', await p.locator('.helper-window').count(), '| height kept', await p.locator('.helper-input textarea').evaluate((e) => e.offsetHeight));
await p.locator('.helper-grip').dblclick();
console.log('dblclick auto', await p.locator('.helper-input textarea').evaluate((e) => e.offsetHeight));
console.log('errors:', errs);
await b.close();
