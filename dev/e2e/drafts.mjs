import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).click();
await p.locator('.panel-tabs button:has-text("Helper")').click();
await p.locator('.helper-input textarea').fill('Half-written idea about Rell');
await p.locator('.composer textarea').fill('Story draft one');
await p.locator('.panel-tabs button:has-text("Codex")').click();
await p.locator('.panel-tabs button:has-text("Helper")').click();
console.log('helper after tab switch:', await p.locator('.helper-input textarea').inputValue());
await p.getByRole('button', { name: '+ New story' }).click();
console.log('keys', await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith('draft')))); console.log('items', await p.locator('.chat-item').allInnerTexts()); console.log('story 2 composer:', JSON.stringify(await p.locator('.composer textarea').inputValue()));
await p.locator('.chat-item').nth(1).click();
await p.waitForTimeout(400);
console.log('story 1 composer:', await p.locator('.composer textarea').inputValue());
await p.reload(); await p.waitForTimeout(800);
await p.locator('.modal-head .icon').click().catch(() => {});
await p.locator('.chat-item').nth(1).click();
if (!(await p.locator('.panel-tabs').count())) await p.locator('.panel-btn').click().catch(() => {});
await p.locator('.panel-tabs button:has-text("Helper")').click();
console.log('after reload: story', await p.locator('.composer textarea').inputValue(), '| helper', await p.locator('.helper-input textarea').inputValue());
console.log('errors:', errs);
await b.close();
