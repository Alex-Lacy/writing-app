import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
const card = p.locator('.card').first();
await card.locator('.provider-more summary').click();
await card.getByLabel('Address (base URL)').fill('http://localhost:8787/v1');
await card.getByLabel('Name', { exact: true }).fill('Mock');
await card.locator('input[type=password]').fill('test-key');
await card.getByText('Test connection').click();
await p.waitForSelector('text=Connected, 2 models');
await card.getByText('Pick models').click();
await p.getByText('Fetch model list').click();
await p.locator('.remote-row button').nth(0).click();
await p.locator('.modal-head .icon').click();
await p.locator('.composer textarea').fill('Mara at the docks SLOP');
await p.keyboard.press('Enter');
await p.waitForSelector('.msg-assistant .cliche-chip');
await p.locator('.cliche-chip').click();
await p.locator('.cliche-item button:has-text("Ignore")').first().click();
await p.waitForTimeout(300);
console.log('after ignore: chip', await p.locator('.cliche-chip').count(), '| highlights', await p.evaluate(() => CSS.highlights.get('cliche')?.size ?? 0));
await p.locator('.composer textarea').fill('Again SLOP');
await p.keyboard.press('Enter');
await p.waitForFunction(() => document.querySelectorAll('.cliche-chip').length === 1);
await p.locator('.cliche-chip').click();
await p.locator('.cliche-list button:has-text("Ignore all")').click();
await p.waitForTimeout(300);
await p.reload(); await p.waitForTimeout(1200);
console.log('after ignore all + reload: chips', await p.locator('.cliche-chip').count(), '| highlights', await p.evaluate(() => CSS.highlights.get('cliche')?.size ?? 0), '| messages', await p.locator('.msg-assistant').count());
console.log('errors:', errs);
await b.close();
