import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
const card = p.locator('.card').first();
await card.locator('.provider-more summary').click();
await card.getByLabel('Address (base URL)').fill('http://localhost:8787/v1');
await card.getByLabel('Name', { exact: true }).fill('Mock');
await card.locator('input[type=password]').fill('test-key');
await card.getByText('Test connection').click();
await p.waitForSelector('text=Connected, 2 models');
await card.getByText('Pick models').click();
await p.getByText('Fetch model list').click();
await p.locator('.remote-row button').nth(0).click();
await p.locator('.remote-row button').nth(1).click().catch(() => {});
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).dispatchEvent('click');
await p.waitForTimeout(800);
const sent = [];
p.on('request', (r) => { if (r.url().includes('/chat/completions')) sent.push(JSON.parse(r.postData() || '{}').model); });
await p.evaluate(async () => { const st = await import('/src/store/store.ts'); st.ui.openHelper('helper-codex'); });
const pick = p.locator('.helper-model select');
console.log('options:', await pick.locator('option').allInnerTexts());
await pick.selectOption({ index: 2 });
const chosen = await pick.locator('option:checked').innerText();
await p.locator('.helper-input textarea').fill('Add a codex entry for Rell');
await p.keyboard.press('Enter');
await p.waitForTimeout(2500);
console.log('chosen:', chosen, '| sent models:', sent);
await p.evaluate(async () => { const st = await import('/src/store/store.ts'); st.ui.openHelper('helper-plot'); });
console.log('plot helper model:', await pick.locator('option:checked').innerText());
await p.evaluate(async () => { const st = await import('/src/store/store.ts'); st.ui.openHelper('helper-codex'); });
console.log('codex remembered:', await pick.locator('option:checked').innerText());
console.log(await p.evaluate(async () => { const st = await import('/src/store/store.ts'); return JSON.stringify([st.useStore.getState().settings.helperModels, localStorage.getItem('lastHelper:' + st.useStore.getState().currentChatId), await p_sel()]); function p_sel() { return document.querySelector('.helper-top .row select')?.value; } }));
console.log('errors:', errs);
await b.close();
