// Outline: write beats, see what's sent, a reply that reaches the beat offers a card, accept moves on.
import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && errs.push(m.text().slice(0, 200)));
p.on('request', (r) => r.url().includes('completions') && console.log('req:', (r.postDataJSON()?.messages?.[0]?.content ?? '').slice(0, 60)));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
const card = p.locator('.card').first();
await card.locator('.provider-more summary').click();
await card.getByLabel('Address (base URL)').fill('http://localhost:8787/v1');
await card.getByLabel('Name', { exact: true }).fill('Mock');
await card.locator('input[type=password]').fill('test-key');
await card.getByText('Test connection').click();
await p.waitForSelector('text=Connected, 2 models');
await card.getByText('Pick models').click();
await p.getByText('Fetch model list').click();
await p.locator('.remote-row button').nth(0).click();
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).click();
await p.locator('.panel-tabs button:has-text("Setup")').click();
await p.locator('.src-outline textarea').fill('Mara arrives in Harrowgate.\n> Rell offers her a job.\nThe job goes wrong at the docks.\nMara learns Rell set her up.');
console.log('nav:', await p.locator('.outline-nav').innerText());
await p.locator('.composer textarea').fill('Mara listens. BEATDONE');
await p.keyboard.press('Enter');
const body = await (await p.waitForResponse((r) => r.url().includes('/chat/completions') && r.request().postData()?.includes('Mara listens'))).request().postDataJSON();
const sent = JSON.stringify(body.messages);
console.log('sent current beat:', sent.includes('Current scene goal: Rell offers her a job.'), '| ahead:', sent.includes('The job goes wrong at the docks. Then: Mara learns'), '| finished beat sent:', sent.includes('Mara arrives in Harrowgate'));
// Moves on by itself by default; the card stays in Suggestions, accepted, for undo.
await p.waitForFunction(() => /Beat 3 of 4/.test(document.querySelector('.outline-nav')?.textContent ?? ''), null, { timeout: 20000 });
await p.locator('.panel-tabs button:has-text("Suggestions")').click();
console.log('card kept for undo:', await p.locator('text=Outline: move to the next beat').count());
await p.locator('.panel-tabs button:has-text("Setup")').click();
console.log('after reply:', await p.locator('.outline-nav').innerText());
await p.locator('.src-outline').screenshot({ path: '/tmp/outline.png' });
console.log('errors:', errs);
await b.close();
