import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
await p.locator('.modal-head .icon').first().click();
await p.getByRole('button', { name: '+ New story' }).dispatchEvent('click');
await p.waitForTimeout(500);
await p.locator('.panel-tabs button:has-text("Setup")').click();
console.log('empty background open:', await p.locator('.src-background textarea').isVisible());
await p.locator('.src-background textarea').fill('Mara Voss hunts a smuggler in a rain-soaked port city. ' .repeat(5));
await p.locator('.src-background .fold-btn').click();
console.log('folded: textarea hidden', !(await p.locator('.src-background textarea').isVisible()), '| preview:', (await p.locator('.src-background .fold-preview').innerText()).slice(0, 40));
await p.reload(); await p.waitForTimeout(1000);
await p.locator('.modal-scrim .modal-head .icon').first().click({ timeout: 1500 }).catch(() => {});
console.log('after reload still folded:', !(await p.locator('.src-background textarea').isVisible()));
await p.locator('.src-background .fold-preview').click();
console.log('preview click opens:', await p.locator('.src-background textarea').isVisible());
await p.locator('.wt-block.src-steering').screenshot({ path: '/tmp/fold.png' }).catch(() => {});
await p.locator('.panel-body').first().screenshot({ path: '/tmp/fold-panel.png' });
console.log('errors:', errs);
await b.close();
