import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1280, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).click();
await p.locator('.helper-head select, .panel select').first().waitFor();
const sel = p.locator('select').filter({ has: p.locator('option[value="helper-plot"]') });
await sel.selectOption('helper-plot');
await p.reload(); await p.waitForTimeout(1000);
await p.locator('.modal-head .icon').click({ timeout: 1500 }).catch(() => {});
console.log('panel open:', await p.locator('.panel-tabs').count() > 0);
console.log('helper after reload:', await sel.inputValue().catch((e) => 'ERR ' + e.message.slice(0, 80)));
await p.locator('.panel-tabs button:has-text("Codex")').click();
await p.reload(); await p.waitForTimeout(1000);
await p.locator('.modal-head .icon').click({ timeout: 1500 }).catch(() => {});
console.log('tab after reload:', await p.locator('.panel-tabs button.active').innerText().catch(() => '?'));
console.log('errors:', errs);
await b.close();
