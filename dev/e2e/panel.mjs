import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).click();
await p.locator('.panel-tabs button:has-text("Helper")').click();
const w = async () => Math.round((await p.locator('.panel').boundingBox()).width);
console.log('start width', await w());
const h = await p.locator('.panel-resize').boundingBox();
await p.mouse.move(h.x + 3, h.y + 300); await p.mouse.down(); await p.mouse.move(h.x - 220, h.y + 300, { steps: 5 }); await p.mouse.up();
console.log('after drag', await w());
await p.reload(); await p.waitForSelector('.modal'); await p.locator('.modal-head .icon').click(); await p.locator('.panel-btn').click(); await p.locator('.panel-tabs button:has-text("Helper")').click();
console.log('after reload', await w());
await p.locator('.panel-wide').click();
console.log('wide', await w());
const ta = p.locator('.helper-input textarea');
const h0 = (await ta.boundingBox()).height;
await ta.fill(Array.from({ length: 12 }, (_, i) => `Line ${i}`).join('\n'));
const bb = await ta.boundingBox();
console.log('box grew', h0, '->', Math.round(bb.height), 'bottom at', Math.round(bb.y + bb.height));
await p.screenshot({ path: '/tmp/panel.png' });
await p.setViewportSize({ width: 400, height: 800 });
await p.waitForTimeout(300);
console.log('mobile width', await w());
console.log('errors:', errs);
await b.close();
