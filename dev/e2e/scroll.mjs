import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: process.env.CHROME });
const p = await b.newPage({ viewport: { width: 1280, height: 600 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
const card = p.locator('.card').first();
await card.locator('.provider-more summary').click();
await card.getByLabel('Address (base URL)').fill('http://localhost:8787/v1');
await card.getByLabel('Name', { exact: true }).fill('Mock');
await card.locator('input[type=password]').fill('test-key');
await card.getByText('Test connection').click();
await p.waitForSelector('text=Connected, 2 models');
await card.getByText('Pick models').click();
await p.getByText('Fetch model list').click();
await p.locator('.remote-row button').nth(0).click();
await p.locator('.modal-head .icon').click();
await p.getByRole('button', { name: '+ New story' }).click();
await p.waitForSelector('.helper');
for (const q of ['one', 'two']) { await p.locator('.helper-input textarea').fill(q); await p.keyboard.press('Enter'); await p.waitForSelector('.helper-input button:has-text("Send")', { timeout: 30000 }); await p.waitForTimeout(300); }
await p.locator('.helper-input textarea').fill('SLOWHELP three');
await p.keyboard.press('Enter');
await p.waitForTimeout(800);
const box = p.locator('.panel-body.helper');
await box.evaluate((el) => el.scrollTo({ top: 0 }));
await p.waitForTimeout(150);
const t1 = await box.evaluate((el) => el.scrollTop);
await p.waitForTimeout(2500);
const t2 = await box.evaluate((el) => el.scrollTop);
console.log('scrollTop stays while streaming:', t1, t2, 'jump button:', await p.locator('.jump-latest').count());
await p.locator('.helper').screenshot({ path: '/tmp/scroll.png' });
await p.locator('.jump-latest').click();
await p.waitForTimeout(1500);
console.log('after jump at bottom:', await box.evaluate((el) => el.scrollHeight - el.scrollTop - el.clientHeight < 40), 'button:', await p.locator('.jump-latest').count());
console.log('errors:', errs);
await b.close();
