import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1280, height: 860 } });
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://127.0.0.1:5173');
await p.waitForSelector('.modal');
const card = p.locator('.card').first();
await card.locator('input').nth(0).fill('Mock');
await card.locator('input').nth(2).fill('http://localhost:8787/v1');
await card.locator('input[type=password]').fill('test-key');
await card.getByText('Test connection').click();
await p.waitForSelector('text=Connected, 2 models');
await card.getByText('Pick models').click();
await p.getByText('Fetch model list').click();
await p.locator('.remote-row button').nth(0).click();
await p.locator('.modal-head .icon').click();
await p.locator('.composer textarea').fill('Mara at the docks SLOP');
await p.keyboard.press('Enter');
await p.waitForSelector('.msg-assistant .cliche-chip');
console.log('chip:', await p.locator('.cliche-chip').innerText());
console.log('highlight ranges:', await p.evaluate(() => CSS.highlights.get('cliche')?.size));
await p.locator('.cliche-chip').click();
await p.locator('.cliche-list button:has-text("Fix all")').click();
await p.waitForSelector('.msg-cards .sg-card');
console.log('inline cards:', await p.locator('.msg-cards .sg-card').count());
await p.screenshot({ path: '/tmp/p3-cliche.png' });
await p.locator('.msg-cards .sg-card button:has-text("Accept")').first().click();
await p.waitForTimeout(300);
console.log('after accept:', (await p.locator('.msg-assistant .msg-body').innerText()).slice(-60));
console.log('chip gone:', await p.locator('.cliche-chip').count() === 0);
// Selection -> rewrite passage
await p.evaluate(() => {
  const el = document.querySelector('.msg-assistant .msg-body p');
  const r = document.createRange(); r.selectNodeContents(el.firstChild); getSelection().removeAllRanges(); getSelection().addRange(r);
});
await p.waitForSelector('.sel-bar');
await p.locator('.sel-bar button').click();
await p.waitForSelector('.rewrite-box .rewrite-quote');
console.log('quote:', (await p.locator('.rewrite-quote').innerText()).slice(0, 50));
await p.locator('.rewrite-box textarea').fill('shorter');
await p.locator('.rewrite-box button:has-text("Rewrite")').click();
await p.waitForSelector('.msg-cards .sg-card');
await p.locator('.msg-cards .sg-card button:has-text("Accept")').first().click();
await p.waitForTimeout(300);
console.log('after passage rewrite:', (await p.locator('.msg-assistant .msg-body').innerText()).slice(0, 60));
// Whole message rewrite -> new version
await p.locator('.msg-assistant').hover();
await p.locator('.msg-assistant .msg-actions button:has-text("Rewrite")').click();
await p.locator('.rewrite-box textarea').fill('more tense');
await p.keyboard.press('Enter');
await p.waitForFunction(() => document.querySelector('.msg-assistant .msg-body')?.textContent.includes('rewritten as asked'));
console.log('versions:', await p.locator('.msg-assistant .swipes span').innerText());
// Proofread user message
await p.locator('.msg-user').hover();
await p.locator('.msg-user .msg-actions button:has-text("Rewrite")').click();
await p.locator('.rewrite-box button:has-text("Proofread")').click();
await p.waitForSelector('.msg-user .msg-cards .sg-card');
console.log('proofread card:', (await p.locator('.msg-user .sg-card').innerText()).replace(/\s+/g, ' ').slice(0, 120));
// Filter tab
await p.locator('.topbar button[title*="Story panel"], .topbar button:has-text("▤")').first().click();
await p.locator('.panel-tabs button:has-text("Cliché")').click();
await p.locator('text=Fix automatically').click();
console.log('rules shown:', await p.locator('.rule-list .switch').count());
await p.screenshot({ path: '/tmp/p3-filter.png' });
await p.locator('.composer textarea').fill('Again SLOP');
await p.keyboard.press('Enter');
await p.waitForFunction(() => [...document.querySelectorAll('.msg-assistant .msg-body')].at(-1)?.textContent.includes('Cold went through her'), null, { timeout: 15000 });
console.log('auto fix applied');
console.log('errors:', errs);
await b.close();
